// Writes film/assets/timing.js (voice line times + scene starts) and film/index.html (scene hosts).
//   node tools/prep.cjs [endSeconds]   -- optional cut for check renders
//   check cut (cold open + part one): node tools/prep.cjs 61.1
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'film');
const V = JSON.parse(fs.readFileSync(path.join(dir, 'assets', 'vo.json'), 'utf8'));
const r = x => Math.round(x * 100) / 100;
const L = (i, f = 0) => V[i].start + (V[i].end - V[i].start) * f;
// [id, file, start]; each scene runs until the next one starts
const scenes = [
  ['hook', 'hook', 0],
  ['crack', 'crack', L(5) - 0.15],
  ['title', 'title', L(7) - 0.15],
  ['card1', 'card1', L(8) - 0.4],
  ['files', 'files', L(9) - 0.2],
  ['street', 'street', L(11) - 0.2],
  ['bars', 'bars', L(14) - 0.2],
  ['card2', 'card2', L(17) - 0.4],
  ['owned', 'owned', L(18) - 0.2],
  ['joneses', 'joneses', L(23) - 0.2],
  ['window', 'window', L(25) - 0.2],
  ['card3', 'card3', L(27) - 0.4],
  ['feed', 'feed', L(28) - 0.2],
  ['paycheck', 'paycheck', L(30) - 0.2],
  ['card4', 'card4', L(32) - 0.4],
  ['fair', 'fair', L(33) - 0.2],
  ['card5', 'card5', L(36) - 0.4],
  ['moves', 'moves', L(37) - 0.2],
  ['close', 'close', L(40) - 0.3],
  ['endcard', 'endcard', L(42) - 0.2],
].map(([id, f, s]) => [id, f, r(s)]);
const total = r(+process.argv[2] || V[V.length - 1].end + 2.5);
const live = scenes.filter(s => s[2] < total);
fs.writeFileSync(path.join(dir, 'assets', 'timing.js'),
  `window.VO = ${JSON.stringify(V.map(v => ({ start: v.start, end: v.end })))};\nwindow.SCENES = ${JSON.stringify(Object.fromEntries(scenes.map(s => [s[0], s[2]])))};\n`);
const hosts = live.map(([id, f, s], i) => {
  const end = i + 1 < live.length ? live[i + 1][2] : total;
  return `      <div id="${id}" data-composition-id="${id}" data-composition-src="compositions/${f}.html"
        data-start="${s}" data-duration="${r(end - s)}" data-track-index="1" data-track-kind="graphics" data-width="1920" data-height="1080"></div>`;
}).join('\n');
fs.writeFileSync(path.join(dir, 'index.html'), `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <script src="assets/timing.js"></script>
    <script src="assets/rig.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: 1920px; height: 1080px; overflow: hidden; background: #1a2b66; }
      #root { width: 100%; height: 100%; position: relative; }
    </style>
  </head>
  <body>
    <!-- The Neighbor Who Won. Generated by tools/prep-film.cjs: edit scenes there. -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="1920" data-height="1080">
${hosts}
      <audio id="vo" src="assets/vo.wav" data-start="0" data-volume="1" data-track-index="2"></audio>
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`);
console.log(live.map(s => s.join(' ')).join('\n'), '\ntotal', total);
